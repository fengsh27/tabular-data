import csv
import pandas as pd

"""
This module is to pre-process tables generated by LLMs(ChatGPT/Gemini) to 
normalize them to facilitate benchmark.
"""

PE_STUDY_COLUMNS = [
    "Characteristic",
    "Exposure",
    "Outcomes",
    "Parameter statistic",
    "Parameter value",
    "Parameter unit",
    "Variantion type",
    "Variation value",
    "Interval type",
    "Lower bound",
    "Upper bound",
    "P value",
    "Study type",
    "Study design",
    "Population",
    "Pregnancy stage",
    "Drug name",
    "Data source",
    "Inclusion criteria",
    "Exclusion criteria",
    "Outcomes",
    "Subject N",
]
PE_STUDY_COLUMNS_MAP = [
    ("P-value", "P value"),
    ("Interval Low Bound", "Lower bound"),
    ("Interval Low", "Lower bound"),
    ("Interval High Bound", "Upper bound"),
    ("Intervale High Bound", "Upper bound"),
    ("Interval High", "Upper bound"),
]


def get_lower_column_name():
    cols = []
    for v in PE_STUDY_COLUMNS:
        cols.append(v.lower())
    return cols


def process_1st_column(rows: list[list[str]]):
    lower_cols = get_lower_column_name()
    headers = rows[0]
    if headers[0].lower() in lower_cols[0]:
        # no NO. column in table, let's insert it
        prc_rows = []
        for ix, row in enumerate(rows):
            prc_row = []
            if ix == 0:
                prc_row.append("")
            else:
                prc_row.append(ix - 1)
            prc_row = prc_row + row
            prc_rows.append(prc_row)
        return prc_rows

    for ix, row in enumerate(rows):
        if ix == 0:
            row[0] = ""
        else:
            row[0] = ix - 1

    return rows


def process_column_names(rows: list[list[str]]):
    lower_cols = get_lower_column_name()
    unknow_col_index = []

    for ix in range(len(rows[0])):
        column = rows[0][ix]
        if ix == 0:
            continue
        found = False
        if len(column.strip()) == 0:
            print(f"Error: the {ix}th column is empty")
            unknow_col_index.append(ix)
            continue
        # Normalize column names
        try:
            col_ix = lower_cols.index(column.strip().lower())
            rows[0][ix] = PE_STUDY_COLUMNS[col_ix]
            found = True
        except ValueError:
            found = False

        # Map column name
        if not found:
            pair = next(
                (x for x in PE_STUDY_COLUMNS_MAP if x[0].lower() == column.strip().lower()),
                None,
            )
            if pair is not None:
                rows[0][ix] = pair[1]
                found = True
            # for pk_col_map in PK_COLUMNS_MAP:
            #     if column.strip().lower() == pk_col_map[0].lower():
            #         rows[0][ix] = pk_col_map[1]
            #         found = True
            #         break
        if not found:
            print(f"Error: can't find column {column}")
            unknow_col_index.append(ix)

    if len(unknow_col_index) == 0:
        return rows

    processed_rows = []
    for row in rows:
        prcssed_row = []
        for ix in range(len(row)):
            if ix not in unknow_col_index:
                prcssed_row.append(row[ix])
        processed_rows.append(prcssed_row)

    return processed_rows


def preprocess_table(csv_file) -> pd.DataFrame:
    with open(csv_file, "r") as fobj:
        reader = csv.reader(fobj)
        csv_rows = list(reader)
        stripped_rows = [[val.replace("\ufeff", "") for val in row] for row in csv_rows]

        rows = process_1st_column(stripped_rows)
        rows = process_column_names(rows)

        output_df = pd.DataFrame(rows[1:], columns=rows[0])

        return output_df


